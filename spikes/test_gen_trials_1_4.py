@pytest.mark.parametrize("name", sorted(FILES))
def test_committed_file_matches_fresh_run_and_sends(name):
    assert (SAMPLES / name).read_bytes() == g4.render(FILES[name]).encode("utf-8"), \
        "regenerate: uv run spikes/gen_trials_1_4.py"
    rows = parsed(name)
    frames, dropped = s.schedule(rows, 60)
    assert frames and dropped == []  # no zero-frame row (the sender's warning never appears)
    assert rows[0].state == s.NEUTRAL and rows[-1].state == s.NEUTRAL
    assert all(r.time.frames for r in rows)
    for f in set(frames):
        s.encode(f)


