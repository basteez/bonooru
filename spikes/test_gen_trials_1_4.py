def _load(name: str):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


s = _load("send_2wicc")
g4 = _load("gen_trials_1_4")

OPTS = g4.Options()
FILES = {tf.name: tf for tf in g4.build(OPTS)}
ALLOWED_MASK = sum(s.CANON_BUTTONS[b] for b in "LRAXY")
A = s.CANON_BUTTONS["A"]
FIELD_RE = re.compile(r"(\w+)=(\d+)f?")


def parse_text(text: str):
    return s.parse_lines(text.splitlines())


def parsed(name: str):
    return parse_text((SAMPLES / name).read_text(encoding="utf-8"))


def tries(rows):
    """(index, row, fields) for every TRY row."""
    out = []
    for i, r in enumerate(rows):
        if r.label.startswith("TRY"):
            out.append((i, r, dict(FIELD_RE.findall(r.label))))
    return out


def family(prefix: str) -> list[str]:
    return sorted(n for n in FILES if n.startswith(prefix))


def frame(r) -> int:
    assert r.time.frames  # all times in frames, never ms
    return s.time_to_frame(r.time, 60)


