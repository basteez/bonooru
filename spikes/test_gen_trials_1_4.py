def test_extension_round_from_the_same_command(tmp_path):
    assert g4.main(["--out-dir", str(tmp_path), "--leads", "0-5,6,8,10,12,15,20,30", "--mods", "sup"]) == 0
    names = sorted(p.name for p in tmp_path.iterdir())
