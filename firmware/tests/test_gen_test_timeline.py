"""Host test F.38 (story 2.5 D8, Task 9.5): the built-in test timeline does not drift.

Run by ctest as `python3 -I test_gen_test_timeline.py FW_DIR` (testtl_drift):
  1. drift: tools/gen_test_timeline.py regenerates testtl_data.c and
     testtl_expected.txt from the committed trial file into a temporary
     directory; both equal the committed files byte for byte;
  2. the source trial file's header says it is generated from the Story 1.5
     profile, and the generated table has the hand-counted 158 events and 62
     notes, the last event NEUTRAL|END;
  3. the generator's own rules on hand-written bad inputs: a forbidden button
     (B, ZL), a forbidden hat (left), a non-increasing time, no final neutral,
     a missing profile header, too many events, a time at 2^31: each refused
     with exit 1 and a message; a good minimal input passes and its last row
     carries the END flag.
Stdlib only, Python 3.9+.
"""

import os
import subprocess
import sys
import tempfile

FW = None
FAILS = []


def check(cond, what):
    if not cond:
        FAILS.append(what)
        print("testtl_drift: FAIL %s" % what)


def gen(src, out_dir):
    out_c = os.path.join(out_dir, "testtl_data.c")
    out_e = os.path.join(out_dir, "testtl_expected.txt")
    p = subprocess.run([sys.executable, "-I", os.path.join(FW, "tools", "gen_test_timeline.py"),
                        "--src", src, "--out-c", out_c, "--out-expected", out_e],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    return p.returncode, p.stdout + p.stderr, out_c, out_e


def read(path):
    with open(path, "rb") as f:
        return f.read()


HEADER = ("# Story 1.6 walking skeleton: test.\n"
          "# Melody: x.melody; profile: app/profiles/oot-switch2-1.1.1.toml.\n")


def bad(tmp, name, body, needle):
    src = os.path.join(tmp, name + ".txt")
    with open(src, "w", encoding="utf-8") as f:
        f.write(body)
    out = os.path.join(tmp, name)
    os.mkdir(out)
    rc, msg, _, _ = gen(src, out)
    check(rc == 1, "%s: exit %d, wanted 1 (%s)" % (name, rc, msg.strip()))
    check(needle in msg, "%s: message %r lacks %r" % (name, msg.strip(), needle))


def main():
    global FW
    if len(sys.argv) != 2:
        sys.exit("usage: test_gen_test_timeline.py FW_DIR")
    FW = os.path.abspath(sys.argv[1])
    repo = os.path.dirname(FW)
    src = os.path.join(repo, "spikes", "samples", "story-1-6", "ode-to-joy-90bpm.txt")
    with open(src, "r", encoding="utf-8") as f:
        head = f.read(2000)
    check("GENERATED by spikes/gen_trials_1_6.py" in head, "trial file header: not generated by gen_trials_1_6.py")
    check("profile: app/profiles/oot-switch2-1.1.1.toml" in head, "trial file header: not from the Story 1.5 profile")

    with tempfile.TemporaryDirectory() as tmp:
        rc, msg, out_c, out_e = gen(src, tmp)
        check(rc == 0, "regeneration failed: %s" % msg.strip())
        if rc == 0:
            check(read(out_c) == read(os.path.join(FW, "controller", "core", "testtl_data.c")),
                  "drift: controller/core/testtl_data.c differs from a fresh generation "
                  "(run python3 firmware/tools/gen_test_timeline.py)")
            check(read(out_e) == read(os.path.join(FW, "tests", "testtl_expected.txt")),
                  "drift: tests/testtl_expected.txt differs from a fresh generation")
            text = read(out_c).decode("utf-8")
            rows = [ln for ln in text.splitlines() if ln.startswith("    {")]
            check(len(rows) == 158, "table rows %d, wanted 158" % len(rows))
            check(rows and rows[-1].startswith("    {44166667u, {0x0000u, 8u, 0x80u, 0x80u, 0x80u, 0x80u, 0x01u}}"),
                  "last row is not NEUTRAL|END at 44166667 us")
            check(sum(1 for r in rows if r.split("}}")[0].endswith("0x01u")) == 1, "not exactly one END row")
            notes = [ln for ln in read(out_e).decode("utf-8").splitlines() if ln and not ln.startswith("#")]
            check(len(notes) == 62, "expected notes %d, wanted 62" % len(notes))
            check(notes and notes[0] == "01 B5 30 500000", "first note %r" % (notes[0] if notes else None))

        bad(tmp, "button_b", HEADER + "0f\n30f B - -\n60f - - -\n", "allow-list")
        bad(tmp, "button_zl", HEADER + "0f\n30f Y+ZL - -\n60f - - -\n", "allow-list")
        bad(tmp, "hat_left", HEADER + "0f\n30f - left -\n60f - - -\n", "allow-list")
        bad(tmp, "not_increasing", HEADER + "0f\n30f Y - -\n30f - - -\n", "not after the previous row")
        bad(tmp, "no_final_neutral", HEADER + "0f\n30f Y - -\n", "no final neutral")
        bad(tmp, "no_header", "# a trial\n0f\n30f Y - -\n60f - - -\n", "Story 1.5 profile")
        bad(tmp, "too_many", HEADER + "".join("%df Y - -\n" % (2 * i) for i in range(400)) + "900f - - -\n",
            "more than 400")
        bad(tmp, "too_late", HEADER + "0f\n128850f - - -\n", "below 2^31")

        good = os.path.join(tmp, "good.txt")
        with open(good, "w", encoding="utf-8") as f:
            f.write(HEADER + "0f - - -\n30f R - 80:00 # NOTE 01 G5 79\n54f - up -\n60f - - -\n")
        out = os.path.join(tmp, "good")
        os.mkdir(out)
        rc, msg, out_c, out_e = gen(good, out)
        check(rc == 0, "good input refused: %s" % msg.strip())
        if rc == 0:
            text = read(out_c).decode("utf-8")
            check("{500000u, {0x0020u, 8u, 0x80u, 0x00u, 0x80u, 0x80u, 0x00u}}" in text,
                  "R + stick up at frame 30 not encoded as buttons 0x0020, lx 80, ly 00")
            check("{900000u, {0x0000u, 0u, 0x80u, 0x80u, 0x80u, 0x80u, 0x00u}}" in text, "hat up not encoded as 0")
            check("{1000000u, {0x0000u, 8u, 0x80u, 0x80u, 0x80u, 0x80u, 0x01u}}" in text, "final END not marked")
            check(read(out_e).decode("utf-8").splitlines()[-1] == "01 G5 30 500000", "expected note row")

    if FAILS:
        return 1
    print("testtl_drift (F.38): ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
